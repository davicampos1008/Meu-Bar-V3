export function allIngredientNames(): string[] {
  const out: string[] = [];
  const seen = new Set<string>();
  Object.keys(CAT).forEach((cat) => {
    (CAT[cat] || []).forEach((s) => {
      const name = String(s).split('|')[0].trim();
      if (name && !seen.has(name)) {
        seen.add(name);
        out.push(name);
      }
    });
  });
  ['Gelo', 'Água', 'Água com gás', 'Açúcar', 'Limão', 'Laranja', 'Hortelã'].forEach((n) => {
    if (!seen.has(n)) {
      seen.add(n);
      out.push(n);
    }
  });
  return out.sort((a, b) => a.localeCompare(b, 'pt-BR'));
}
